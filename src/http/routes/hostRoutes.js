export const hostRoutes = Router();
hostRoutes.use(requireAdmin);

async function getHostSettings() {
  return HostSettings.findOneAndUpdate(
    { key: "hosts" },
    { $setOnInsert: { defaultNameTemplate: "호기 {n}" } },
    { returnDocument: "after", upsert: true, setDefaultsOnInsert: true },
  );
}

function isDiscordInviteLink(value, clientId) {
  try {
    const url = new URL(value);
    const scopes = (url.searchParams.get("scope") ?? "").split(/[+\s]/).filter(Boolean);
    return url.protocol === "https:" && url.hostname === "discord.com" && url.pathname === "/oauth2/authorize" && url.searchParams.get("client_id") === clientId && (!scopes.length || scopes.includes("bot"));
  } catch { return false; }
}

function escapeRegex(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function getGeneratedNameIndex(name, template) {
  const parts = template.split("{n}").map(escapeRegex);
  const matcher = new RegExp("^" + parts[0] + "(\\d+)" + parts.slice(1).join("\\1") + "$");
  const match = String(name).match(matcher);
  return match ? Number(match[1]) : null;
}

function publicHost(host, recovering = false, lastRecoveryAt = null, hostNumber = null) {
  const botOnline = getHostBotStatus(host._id).online;
  return {
    _id: host._id,
    hostNumber,
    name: host.name,
    clientId: host.clientId,
    inviteLink: host.inviteLink ?? "",
    hasClientSecret: Boolean(host.clientSecret),
    hasBotToken: Boolean(host.botToken),
    enabled: host.enabled,
    botOnline,
    runtimeStatus: recovering ? "recovering" : botOnline ? "on" : "off",
    memberCount: host.memberCount ?? 0,
    activeMemberCount: host.activeMemberCount ?? 0,
    statsSyncedAt: host.statsSyncedAt ?? null,
    lastRecoveryAt: lastRecoveryAt ?? host.lastRecoveryAt ?? null,
    createdAt: host.createdAt,
    updatedAt: host.updatedAt,
  };
}

hostRoutes.get("/settings", async (_request, response) => {
  const [settings, hostCount] = await Promise.all([getHostSettings(), BotHost.countDocuments()]);
  return response.json({ defaultNameTemplate: settings.defaultNameTemplate, hostCount });
});

hostRoutes.put("/settings", async (request, response) => {
  const template = String(request.body?.defaultNameTemplate ?? "").trim();
  if (!template || template.length > 80 || !template.includes("{n}")) {
    return response.status(400).json({ error: "기본 이름에 {n}을 포함해 주세요." });
  }
  const currentSettings = await getHostSettings();
  const hosts = await BotHost.find().sort({ createdAt: 1, _id: 1 }).lean();
  const generated = hosts.flatMap((host, position) => {
    const matchedIndex = getGeneratedNameIndex(host.name, currentSettings.defaultNameTemplate);
    if (host.nameAutoGenerated !== true && matchedIndex === null) return [];
    return [{ host, index: host.nameIndex ?? matchedIndex ?? position + 1 }];
  });
  const generatedIds = new Set(generated.map(({ host }) => String(host._id)));
  const reservedNames = new Set(hosts.filter((host) => !generatedIds.has(String(host._id))).map((host) => host.name));
  const renamed = new Set();
  for (const { host, index } of generated) {
    const nextName = template.replaceAll("{n}", String(index));
    if (reservedNames.has(nextName) || renamed.has(nextName)) {
      return response.status(409).json({ error: `기본 이름 패턴으로 만든 '${nextName}'이 기존 호기 이름과 중복됩니다.` });
    }
    renamed.add(nextName);
  }
  if (generated.length) {
    await BotHost.bulkWrite(generated.map(({ host, index }) => ({
      updateOne: {
        filter: { _id: host._id },
        update: { $set: { name: template.replaceAll("{n}", String(index)), nameAutoGenerated: true, nameIndex: index } },
      },
    })));
  }
  const settings = await HostSettings.findOneAndUpdate(
    { key: "hosts" },
    { defaultNameTemplate: template },
    { returnDocument: "after", upsert: true, runValidators: true },
  );
  return response.json({ defaultNameTemplate: settings.defaultNameTemplate });
});

hostRoutes.get("/", async (_request, response) => {
  const hosts = await BotHost.find().sort({ createdAt: 1, _id: 1 }).lean();
  const runningRuns = await RecoveryRun.find({
    hostIds: { $in: hosts.map((host) => host._id) },
    status: { $in: ["QUEUED", "RUNNING"] },
  }).select("hostIds").lean();
  const recoveringHostIds = new Set(runningRuns.flatMap((run) => run.hostIds.map(String)));
  const recentRuns = await RecoveryRun.aggregate([
    { $match: { hostIds: { $in: hosts.map((host) => host._id) }, startedAt: { $ne: null } } },
    { $unwind: "$hostIds" },
    { $match: { hostIds: { $in: hosts.map((host) => host._id) } } },
    { $sort: { startedAt: -1 } },
    { $group: { _id: "$hostIds", lastRecoveryAt: { $first: "$startedAt" } } },
  ]);
  const lastRunByHostId = new Map(recentRuns.map((run) => [String(run._id), run.lastRecoveryAt]));
  return response.json({ hosts: hosts.map((host, index) => publicHost(
    host,
    recoveringHostIds.has(String(host._id)),
    lastRunByHostId.get(String(host._id)),
    index + 1,
  )) });
});

hostRoutes.get("/db-info/:hostNumber", async (request, response) => {
  const hostNumber = Number(request.params.hostNumber);
  if (!Number.isSafeInteger(hostNumber) || hostNumber < 1 || hostNumber > 10000) {
    return response.status(400).json({ error: "호기 번호가 올바르지 않습니다." });
  }
  const [host] = await BotHost.find().sort({ createdAt: 1, _id: 1 }).skip(hostNumber - 1).limit(1).lean();
  if (!host) return response.status(404).json({ error: "해당 번호의 호기를 찾을 수 없습니다." });
  const users = await RestoredUser.find({ hostId: host._id })
    .select("discordUserId username email status lastUpdated tokenExpiresAt")
    .sort({ lastUpdated: -1, username: 1 })
    .lean();
  const publicUser = (user) => ({
    _id: user._id,
    userId: user.discordUserId,
    username: user.username,
    email: user.email ?? null,
    status: user.status,
    lastUpdated: user.lastUpdated,
    tokenExpiresAt: user.tokenExpiresAt ?? null,
  });
  return response.json({
    host: { name: host.name, hostNumber },
    activeUsers: users.filter((user) => user.status === "ACTIVE").map(publicUser),
    expiredUsers: users.filter((user) => user.status !== "ACTIVE").map(publicUser),
  });
});

hostRoutes.post("/:hostId/sync", async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.hostId)) return response.status(400).json({ error: "호기 ID가 올바르지 않습니다." });
  await refreshHostBots();
  const result = await syncHostStats(request.params.hostId, { allowOffline: true });
  if (!result.synced) return response.status(409).json({ error: result.reason });
  const host = await BotHost.findById(request.params.hostId).lean();
  return response.json({ host: publicHost(host) });
});

hostRoutes.post("/", async (request, response) => {
  const clientId = String(request.body?.clientId ?? "").trim();
  const inviteLink = String(request.body?.inviteLink ?? "").trim();
  const clientSecret = String(request.body?.clientSecret ?? "").trim();
  const botToken = String(request.body?.botToken ?? "").trim();
  if (!/^\d{17,22}$/.test(clientId) || !clientSecret || clientSecret.length > 512 || !botToken || botToken.length > 2048 || (inviteLink && !isDiscordInviteLink(inviteLink, clientId))) {
    return response.status(400).json({ error: "Client ID, Client Secret, 봇 토큰을 확인해 주세요." });
  }
  const settings = await getHostSettings();
  const nameIndex = (await BotHost.countDocuments()) + 1;
  const name = settings.defaultNameTemplate.replaceAll("{n}", String(nameIndex));
  const host = await BotHost.create({
    name,
    nameAutoGenerated: true,
    nameIndex,
    clientId,
    inviteLink,
    clientSecret: encryptSecret(clientSecret, config.tokenEncryptionKey),
    botToken: encryptSecret(botToken, config.tokenEncryptionKey),
  });
  await refreshHostBots();
  if (getHostBotStatus(host._id).online) await syncHostStats(host._id);
  const savedHost = await BotHost.findById(host._id).lean();
  return response.status(201).json({ host: publicHost(savedHost) });
});

hostRoutes.patch("/:hostId", async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.hostId)) return response.status(400).json({ error: "호기 ID가 올바르지 않습니다." });
  const update = {};
  const { name, clientId, inviteLink, clientSecret, botToken, enabled } = request.body ?? {};
  if (name !== undefined) {
    if (typeof name !== "string" || !name.trim() || name.trim().length > 80) return response.status(400).json({ error: "호기 이름을 확인해 주세요." });
    update.name = name.trim();
    const currentHost = await BotHost.findById(request.params.hostId).select("name").lean();
    if (currentHost && currentHost.name !== update.name) update.nameAutoGenerated = false;
  }
  if (clientId !== undefined) {
    const value = String(clientId).trim();
    if (!/^\d{17,22}$/.test(value)) return response.status(400).json({ error: "Client ID는 Discord 앱 ID 형식으로 입력해 주세요." });
    update.clientId = value;
    if (inviteLink === undefined) update.inviteLink = "";
  }
  if (inviteLink !== undefined) {
    const value = String(inviteLink).trim();
    if (value && !isDiscordInviteLink(value, String(clientId ?? "").trim() || String((await BotHost.findById(request.params.hostId).select("clientId").lean())?.clientId ?? ""))) return response.status(400).json({ error: "Discord OAuth 봇 초대 링크를 확인해 주세요." });
    update.inviteLink = value;
  }
  if (clientSecret !== undefined && String(clientSecret).trim()) {
    const value = String(clientSecret).trim();
    if (value.length > 512) return response.status(400).json({ error: "Client Secret 길이를 확인해 주세요." });
    update.clientSecret = encryptSecret(value, config.tokenEncryptionKey);
  }
  if (botToken !== undefined && String(botToken).trim()) {
    const value = String(botToken).trim();
    if (value.length > 2048) return response.status(400).json({ error: "봇 토큰 길이를 확인해 주세요." });
    update.botToken = encryptSecret(value, config.tokenEncryptionKey);
  }
  if (enabled !== undefined) {
    if (typeof enabled !== "boolean") return response.status(400).json({ error: "사용 상태가 올바르지 않습니다." });
    update.enabled = enabled;
  }
  if (!Object.keys(update).length) return response.status(400).json({ error: "변경할 항목이 없습니다." });
  const host = await BotHost.findByIdAndUpdate(request.params.hostId, update, { returnDocument: "after", runValidators: true }).lean();
  if (!host) return response.status(404).json({ error: "호기를 찾을 수 없습니다." });
  await refreshHostBots();
  if (host.enabled && getHostBotStatus(host._id).online) await syncHostStats(host._id);
  const savedHost = await BotHost.findById(host._id).lean();
  return response.json({ host: publicHost(savedHost) });
});

hostRoutes.delete("/:hostId", async (request, response) => {
  if (!mongoose.isValidObjectId(request.params.hostId)) return response.status(400).json({ error: "호기 ID가 올바르지 않습니다." });
  const [userCount, licenseCount, productCount] = await Promise.all([
    RestoredUser.countDocuments({ hostId: request.params.hostId }),
    License.countDocuments({ hostIds: request.params.hostId }),
    Product.countDocuments({ hostIds: request.params.hostId }),
  ]);
  if (userCount > 0 || licenseCount > 0 || productCount > 0) return response.status(409).json({ error: "연결된 유저·라이선스·상품 데이터가 있어 호기를 삭제할 수 없습니다. 먼저 비활성화해 주세요." });
  const result = await BotHost.deleteOne({ _id: request.params.hostId });
  if (!result.deletedCount) return response.status(404).json({ error: "호기를 찾을 수 없습니다." });
  await refreshHostBots();
  return response.status(204).end();
});












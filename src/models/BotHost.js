import mongoose from "mongoose";
import { encryptedSecretSchema } from "./fields/encryptedSecret.js";

const botHostSchema = new mongoose.Schema(
  {
    name: { type: String, required: true, trim: true },
    nameAutoGenerated: { type: Boolean, default: false },
    nameIndex: { type: Number, min: 1 },
    clientId: { type: String, required: true, trim: true },
    inviteLink: { type: String, trim: true, default: "" },
    clientSecret: { type: encryptedSecretSchema, required: true },
    botToken: { type: encryptedSecretSchema, required: true },
    enabled: { type: Boolean, default: true },
    memberCount: { type: Number, min: 0, default: 0 },
    activeMemberCount: { type: Number, min: 0, default: 0 },
    statsSyncedAt: { type: Date, default: null },
    lastRecoveryAt: { type: Date, default: null },
    runtimeHeartbeatAt: { type: Date, default: null },
    runtimeUsername: { type: String, default: "", trim: true },
  },
  { timestamps: true },
);

botHostSchema.index({ name: 1 }, { unique: true });

export const BotHost = mongoose.model("BotHost", botHostSchema);


